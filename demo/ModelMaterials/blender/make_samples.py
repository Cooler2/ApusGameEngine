"""Build the stock material samples, export them to AEM and render a Blender reference.

Run from the engine root with Blender 4.5:
    blender -b --factory-startup -P demo/ModelMaterials/blender/make_samples.py

Output:
    demo/ModelMaterials/res/models/*.aem and textures/  - one asset per sample, at its own origin
    demo/ModelMaterials/blender/samples.blend           - the scene, to inspect the materials
    demo/ModelMaterials/blender/reference.png           - Blender render of the scene

The reference light matches the engine light of the demo: World color = ambient,
Sun strength = pi x direct light power. View transform Standard.
"""

from math import cos, pi, radians, sin
import os
import sys

import bpy
from mathutils import Vector

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
MODELS = os.path.join(HERE, "..", "res", "models")
TEXTURES = os.path.join(MODELS, "textures")
sys.path.insert(0, os.path.join(ROOT, "tools", "blender"))
from io_export_aem.export_mesh import export_aem  # noqa: E402

AMBIENT = (0.12, 0.12, 0.14)       # linear, engine ambient light
SUN_DIRECTION = (0.4, -0.6, 0.7)   # towards the sun, engine direct light
SUN_POWER = 1.0                    # engine direct light power
CAMERA_POS = (0.0, -12.0, 12.0)
CAMERA_TARGET = (0.0, 1.8, 0.3)
SPACING = 3.0


def srgb_to_linear(value):
    return value / 12.92 if value <= 0.04045 else ((value + 0.055) / 1.055) ** 2.4


def srgb(r, g, b):
    """Linear color from 0..255 sRGB values, as picked with the Hex field."""
    return tuple(srgb_to_linear(c / 255) for c in (r, g, b)) + (1.0,)


def reset_scene():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.unit_settings.system = "METRIC"
    return scene


def principled(name):
    material = bpy.data.materials.new(name)
    material.use_nodes = True
    material.use_backface_culling = True
    bsdf = material.node_tree.nodes["Principled BSDF"]
    return material, bsdf


def save_image(name, size, pixel):
    """Write a PNG generated by pixel(x, y) -> sRGB RGBA in 0..1 and load it back as a file image."""
    os.makedirs(TEXTURES, exist_ok=True)
    path = os.path.join(TEXTURES, name + ".png")
    image = bpy.data.images.new(name, size, size, alpha=True)
    pixels = []
    for y in range(size):
        for x in range(size):
            # Blender stores rows bottom-up.
            pixels.extend(pixel(x, size - 1 - y))
    image.pixels = pixels
    image.filepath_raw = path
    image.file_format = "PNG"
    image.save()
    bpy.data.images.remove(image)
    return bpy.data.images.load(path)


def image_node(material, image, location=(-500, 300)):
    node = material.node_tree.nodes.new("ShaderNodeTexImage")
    node.image = image
    node.location = location
    return node


def sphere(name, segments=48, rings=24):
    """Smooth UV sphere of radius 1 standing on the ground.

    Built from explicit lists: the Blender primitive orders its faces differently from
    run to run, which would make the exported files differ."""
    vertices = [(0.0, 0.0, 2.0)]
    for ring in range(1, rings):
        z = cos(pi * ring / rings)
        r = sin(pi * ring / rings)
        for segment in range(segments):
            a = 2 * pi * segment / segments
            vertices.append((r * cos(a), r * sin(a), 1.0 + z))
    vertices.append((0.0, 0.0, 0.0))
    bottom = len(vertices) - 1

    def ring_vertex(ring, segment):
        return 1 + (ring - 1) * segments + segment % segments
    faces = [(0, ring_vertex(1, s), ring_vertex(1, s + 1)) for s in range(segments)]
    for ring in range(1, rings - 1):
        for s in range(segments):
            faces.append((ring_vertex(ring, s), ring_vertex(ring + 1, s),
                          ring_vertex(ring + 1, s + 1), ring_vertex(ring, s + 1)))
    faces += [(ring_vertex(rings - 1, s), bottom, ring_vertex(rings - 1, s + 1)) for s in range(segments)]
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(vertices, [], faces)
    mesh.shade_smooth()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    return obj


def cube(name):
    bpy.ops.mesh.primitive_cube_add(size=1.6, location=(0, 0, 0.8))
    obj = bpy.context.object
    obj.name = name
    return obj


def assign(obj, material):
    obj.data.materials.clear()
    obj.data.materials.append(material)


# --- samples: each returns the object, built at the origin ---

def glossy_green():
    obj = sphere("GlossyGreen")
    material, bsdf = principled("GlossyGreen")
    bsdf.inputs["Base Color"].default_value = srgb(140, 230, 120)
    bsdf.inputs["Roughness"].default_value = 0.2
    assign(obj, material)
    return obj


def matte_green():
    obj = sphere("MatteGreen")
    material, bsdf = principled("MatteGreen")
    bsdf.inputs["Base Color"].default_value = srgb(140, 230, 120)
    bsdf.inputs["Roughness"].default_value = 0.9
    assign(obj, material)
    return obj


def gold():
    obj = sphere("Gold")
    material, bsdf = principled("Gold")
    bsdf.inputs["Base Color"].default_value = srgb(255, 200, 90)
    bsdf.inputs["Metallic"].default_value = 1.0
    bsdf.inputs["Roughness"].default_value = 0.3
    assign(obj, material)
    return obj


def corner_colors(obj, colors):
    attribute = obj.data.color_attributes.new("Col", "BYTE_COLOR", "POINT")
    for vertex in obj.data.vertices:
        attribute.data[vertex.index].color_srgb = colors(vertex.co)
    obj.data.color_attributes.active_color = attribute
    obj.data.color_attributes.render_color_index = obj.data.color_attributes.active_color_index


def red_corner():
    obj = cube("RedCorner")
    corner_colors(obj, lambda co: (1.0, 0.0, 0.0, 1.0) if co.x > 0 and co.y < 0 and co.z > 0
                  else (1.0, 1.0, 1.0, 1.0))
    material, bsdf = principled("VertexColor")
    attribute = material.node_tree.nodes.new("ShaderNodeVertexColor")
    attribute.location = (-400, 300)
    material.node_tree.links.new(attribute.outputs["Color"], bsdf.inputs["Base Color"])
    assign(obj, material)
    return obj


def tinted_vertex_colors():
    """Vertex colors multiplied by a constant through a Mix node."""
    obj = cube("TintedVertexColors")
    corner_colors(obj, lambda co: (0.5 + co.x * 0.6, 0.5 + co.y * 0.6, 0.5 + co.z * 0.6, 1.0))
    material, bsdf = principled("TintedVertexColors")
    nodes, links = material.node_tree.nodes, material.node_tree.links
    attribute = nodes.new("ShaderNodeVertexColor")
    attribute.location = (-600, 300)
    mix = nodes.new("ShaderNodeMix")
    mix.data_type = "RGBA"
    mix.blend_type = "MULTIPLY"
    mix.location = (-300, 300)
    mix.inputs["Factor"].default_value = 1.0
    links.new(attribute.outputs["Color"], next(s for s in mix.inputs if s.identifier == "A_Color"))
    next(s for s in mix.inputs if s.identifier == "B_Color").default_value = srgb(255, 220, 160)
    links.new(next(s for s in mix.outputs if s.identifier == "Result_Color"), bsdf.inputs["Base Color"])
    bsdf.inputs["Roughness"].default_value = 0.6
    assign(obj, material)
    return obj


def unused_vertex_colors():
    """The mesh carries colors, but the material does not use them: the engine must ignore them."""
    obj = cube("UnusedVertexColors")
    corner_colors(obj, lambda co: (0.0, 0.0, 0.0, 1.0) if co.z > 0 else (1.0, 0.0, 1.0, 1.0))
    material, bsdf = principled("PlainBlue")
    bsdf.inputs["Base Color"].default_value = srgb(90, 140, 230)
    bsdf.inputs["Roughness"].default_value = 0.5
    assign(obj, material)
    return obj


def checker():
    obj = cube("Checker")
    image = save_image("checker", 64, lambda x, y: (0.95, 0.85, 0.3, 1.0) if (x // 8 + y // 8) % 2
                       else (0.2, 0.3, 0.7, 1.0))
    material, bsdf = principled("Checker")
    texture = image_node(material, image)
    material.node_tree.links.new(texture.outputs["Color"], bsdf.inputs["Base Color"])
    assign(obj, material)
    return obj


def cutout():
    bpy.ops.mesh.primitive_plane_add(size=2.0, location=(0, 0, 1.0), rotation=(radians(90), 0, 0))
    obj = bpy.context.object
    obj.name = "Cutout"
    bpy.ops.object.transform_apply(location=False, rotation=True, scale=False)

    def grid(x, y):
        bar = x % 16 < 4 or y % 16 < 4
        return (0.85, 0.35, 0.2, 1.0) if bar else (0.0, 0.0, 0.0, 0.0)
    image = save_image("grid", 64, grid)
    material, bsdf = principled("Grid")
    material.use_backface_culling = False
    material.surface_render_method = "DITHERED"
    texture = image_node(material, image)
    material.node_tree.links.new(texture.outputs["Color"], bsdf.inputs["Base Color"])
    material.node_tree.links.new(texture.outputs["Alpha"], bsdf.inputs["Alpha"])
    assign(obj, material)
    return obj


def emissive():
    obj = cube("Emissive")
    material, bsdf = principled("Glow")
    bsdf.inputs["Base Color"].default_value = srgb(40, 40, 40)
    bsdf.inputs["Emission Color"].default_value = srgb(255, 150, 40)
    bsdf.inputs["Emission Strength"].default_value = 1.0
    assign(obj, material)
    return obj


def no_material():
    obj = sphere("NoMaterial")
    obj.data.materials.clear()
    return obj


SAMPLES = (
    glossy_green, matte_green, gold,
    red_corner, tinted_vertex_colors, unused_vertex_colors,
    checker, cutout, emissive, no_material,
)


def export_sample(obj):
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    path = os.path.join(MODELS, obj.name + ".aem")
    has_colors = len(obj.data.color_attributes) > 0
    double_sided = not obj.active_material.use_backface_culling if obj.active_material else False
    warnings = export_aem(bpy.context, path, export_colors=has_colors, double_sided=double_sided)
    for warning in warnings:
        print(f"WARNING {obj.name}: {warning}")
    print(f"EXPORTED {os.path.relpath(path, ROOT)}")


def grid_position(index):
    columns = 5
    row, column = divmod(index, columns)
    return Vector(((column - (columns - 1) / 2) * SPACING, row * SPACING * 1.6, 0.0))


def setup_reference(scene):
    world = bpy.data.worlds.new("Ambient")
    world.use_nodes = True
    world.node_tree.nodes["Background"].inputs["Color"].default_value = (*AMBIENT, 1.0)
    world.node_tree.nodes["Background"].inputs["Strength"].default_value = 1.0
    scene.world = world

    sun_data = bpy.data.lights.new("Sun", "SUN")
    sun_data.energy = pi * SUN_POWER
    sun_data.angle = radians(0.5)
    sun_data.use_shadow = False
    sun = bpy.data.objects.new("Sun", sun_data)
    scene.collection.objects.link(sun)
    sun.rotation_euler = Vector(SUN_DIRECTION).to_track_quat("Z", "Y").to_euler()

    camera_data = bpy.data.cameras.new("Camera")
    camera_data.lens = 32
    camera = bpy.data.objects.new("Camera", camera_data)
    scene.collection.objects.link(camera)
    camera.location = CAMERA_POS
    direction = Vector(CAMERA_TARGET) - Vector(CAMERA_POS)
    camera.rotation_euler = direction.to_track_quat("-Z", "Y").to_euler()
    scene.camera = camera

    scene.render.engine = "BLENDER_EEVEE_NEXT"
    scene.render.resolution_x = 1280
    scene.render.resolution_y = 720
    scene.render.film_transparent = False
    scene.view_settings.view_transform = "Standard"
    scene.view_settings.look = "None"
    scene.view_settings.exposure = 0.0
    scene.view_settings.gamma = 1.0
    scene.render.image_settings.file_format = "PNG"
    scene.render.filepath = os.path.join(HERE, "reference.png")


def main():
    scene = reset_scene()
    os.makedirs(MODELS, exist_ok=True)
    objects = [build() for build in SAMPLES]
    for index, obj in enumerate(objects):
        export_sample(obj)
        obj.location += grid_position(index)
    setup_reference(scene)
    bpy.context.preferences.filepaths.save_version = 0  # no .blend1 backup
    bpy.ops.wm.save_as_mainfile(filepath=os.path.join(HERE, "samples.blend"), relative_remap=True, compress=True)
    bpy.ops.render.render(write_still=True)
    print("REFERENCE", os.path.relpath(scene.render.filepath, ROOT))


main()
