#!/usr/bin/env python
"""
gen_case_tables.py  -  Unicode case tables for Apus.Strings (Base/caseTables.inc).

Builds the simple (1:1) case mappings from UnicodeData.txt: fields 12 (uppercase)
and 13 (lowercase). Full mappings (ß -> SS) and locale rules (Turkish i) are not
covered - they change the character count, which a 1:1 table cannot express.

Layout: a code point splits into a block number (cp shr BLOCK_BITS) and an offset
in the block. The per-direction index maps the block number to a block of the
shared pool; a pool entry is the delta to add to the low 16 bits of the code point
(0 - no mapping). All mappings stay within their 64K plane (checked below), so
the delta is a word that wraps around. Block 0 of the pool is all zeros, identical
blocks are stored once.

Usage:
  python gen_case_tables.py UnicodeData.txt VERSION [output.inc]

UnicodeData.txt: https://www.unicode.org/Public/<version>/ucd/UnicodeData.txt
The output defaults to ../Base/caseTables.inc next to this script.
"""
import os, sys

BLOCK_BITS = 6
BLOCK = 1 << BLOCK_BITS


def load(path):
  upper, lower = {}, {}
  for line in open(path, encoding='ascii'):
    f = line.split(';')
    cp = int(f[0], 16)
    if f[12]: upper[cp] = int(f[12], 16)
    if f[13]: lower[cp] = int(f[13], 16)
  return upper, lower


def main():
  if len(sys.argv) < 3:
    sys.exit(__doc__)
  src, version = sys.argv[1], sys.argv[2]
  out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(
    os.path.dirname(os.path.abspath(__file__)), '..', 'Base', 'caseTables.inc')

  upper, lower = load(src)
  maxCp = max(max(upper), max(lower))
  for m in (upper, lower):
    for a, b in m.items():
      assert a >> 16 == b >> 16, 'mapping crosses a 64K plane: %X -> %X' % (a, b)
  blocks = (maxCp >> BLOCK_BITS) + 1
  assert blocks * BLOCK - 1 >= maxCp

  pool = [tuple([0] * BLOCK)]
  poolIndex = {pool[0]: 0}

  def build(m):
    index = []
    for blk in range(blocks):
      deltas = tuple((m[cp] - cp) & 0xFFFF if cp in m else 0
                     for cp in range(blk * BLOCK, (blk + 1) * BLOCK))
      if deltas not in poolIndex:
        poolIndex[deltas] = len(pool)
        pool.append(deltas)
      index.append(poolIndex[deltas])
    return index

  lowerIndex = build(lower)
  upperIndex = build(upper)
  assert len(pool) <= 256, 'block numbers do not fit in a byte'

  def rows(values, fmt, perLine):
    items = [fmt % v for v in values]
    lines = [','.join(items[i:i + perLine]) for i in range(0, len(items), perLine)]
    return ',\r\n    '.join(lines)

  text = []
  text.append('// Simple Unicode case mappings, Unicode %s (UnicodeData.txt fields 12 and 13).' % version)
  text.append('// Generated by tools/gen_case_tables.py - do not edit, regenerate.')
  text.append('// Lookup: delta:=caseDeltas[index[cp shr CASE_BLOCK_BITS] shl CASE_BLOCK_BITS+cp and CASE_BLOCK_MASK],')
  text.append('// then the low 16 bits of cp are cp+delta (wrapping); 0 - no mapping.')
  text.append('const')
  text.append('  CASE_BLOCK_BITS = %d;' % BLOCK_BITS)
  text.append('  CASE_BLOCK_MASK = $%X;' % (BLOCK - 1))
  text.append('  CASE_MAX_CP = $%X; // no case mappings above' % (blocks * BLOCK - 1))
  text.append('type')
  text.append('  TCaseIndex=array[0..%d] of byte;' % (blocks - 1))
  text.append('const')
  for name, index in (('caseLowerIndex', lowerIndex), ('caseUpperIndex', upperIndex)):
    text.append('  %s:TCaseIndex=(' % name)
    text.append('    ' + rows(index, '%d', 32) + ');')
  text.append('  caseDeltas:array[0..%d] of word=(' % (len(pool) * BLOCK - 1))
  flat = [d for blk in pool for d in blk]
  text.append('    ' + rows(flat, '$%.4X', 16) + ');')
  text.append('')

  with open(out, 'w', encoding='ascii', newline='') as f:
    f.write('\r\n'.join(text))
  print('%s: %d mappings to lower, %d to upper, %d blocks of %d, %d pool blocks, %d bytes of data'
        % (out, len(lower), len(upper), blocks, BLOCK, len(pool),
           2 * blocks + len(pool) * BLOCK * 2))


if __name__ == '__main__':
  main()
